//! Executing exported Noir functions from Rust (feature `runner`, on by default).
//!
//! The runtime works directly on the program artifact that `nargo export` produced, so no Noir
//! sources, `Nargo.toml`, or `nargo` binary are needed at run time:
//!
//! 1. [`Program::from_json`] decodes the artifact (ACIR bytecode + ABI) once.
//! 2. [`Program::execute`] ABI-encodes an [`InputMap`], solves the circuit with the ACVM and the
//!    BN254 black-box solver, and decodes the return value.
//! 3. [`ToInputValue`] / [`FromOutputValue`] convert between Rust values and Noir's
//!    [`InputValue`] representation.
//!
//! Code generated by `nrg!` wraps these steps in a typed `simulate` function and caches the parsed
//! [`Program`] in a `static`, so you rarely need this module directly. It is public for tooling and
//! for programs whose exports are only known at run time.
//!
//! # Example
//!
//! ```
//! use noi_core::runtime::{Client, InputMap, Program, ToInputValue, FromOutputValue};
//!
//! # let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../examples/demo/noir/export/add.json");
//! let program = Program::from_file(path)?;
//!
//! let mut inputs = InputMap::new();
//! inputs.insert("a".into(), 2u32.to_input_value());
//! inputs.insert("b".into(), 3u32.to_input_value());
//!
//! let execution = program.execute(&Client::new(), &inputs)?;
//! let sum = u32::from_output_value(execution.into_return_value().unwrap())?;
//! assert_eq!(sum, 5);
//! # Ok::<(), anyhow::Error>(())
//! ```
//!
//! # Version compatibility
//!
//! Artifacts must come from the Noir version this crate is built against ([`crate::NOIR_VERSION`]);
//! the bytecode serialization changes between Noir releases. A mismatch is reported when the
//! artifact is loaded, not as a confusing execution failure.

use std::{
    fmt,
    path::{Path, PathBuf},
};

use acvm::{acir::native_types::WitnessStack, AcirField};
use anyhow::{anyhow, Context, Result};
use bn254_blackbox_solver::Bn254BlackBoxSolver;
use nargo::{foreign_calls::DefaultForeignCallBuilder, ops::execute_program};
use noirc_abi::Abi;
use noirc_artifacts::program::ProgramArtifact;

pub use acvm::FieldElement;
pub use noirc_abi::{input_parser::InputValue, InputMap};

/// Execution settings shared by every call.
///
/// `Client` is cheap to clone and holds no open resources. The defaults suit library and server
/// use: Noir `println` output is discarded and oracle calls other than the built-in test mocks fail.
///
/// ```
/// let client = noi_core::runtime::Client::new()
///     .with_output(true) // forward Noir `println` to stdout
///     .with_oracle_resolver("http://localhost:5555");
/// assert!(client.shows_output());
/// ```
#[derive(Clone, Debug, Default)]
#[non_exhaustive]
pub struct Client {
    show_output: bool,
    oracle_resolver: Option<String>,
    program_dir: Option<PathBuf>,
    #[cfg(feature = "prove")]
    prover: crate::prove::Prover,
}

impl Client {
    /// Creates a client with default settings.
    pub fn new() -> Self {
        Self::default()
    }

    /// Forwards Noir `println`/`print` output to stdout when `true`. Defaults to `false`.
    pub fn with_output(mut self, show: bool) -> Self {
        self.show_output = show;
        self
    }

    /// Sends unknown oracle (foreign) calls to a JSON-RPC resolver at `url`, as
    /// `nargo execute --oracle-resolver` does.
    pub fn with_oracle_resolver(mut self, url: impl Into<String>) -> Self {
        self.oracle_resolver = Some(url.into());
        self
    }

    /// Root directory of the Noir package. Only forwarded to the oracle resolver; execution itself
    /// never reads from disk.
    pub fn with_program_dir(mut self, dir: impl Into<PathBuf>) -> Self {
        self.program_dir = Some(dir.into());
        self
    }

    /// Proving settings used by generated `prove`/`verify` functions (feature `prove`).
    #[cfg(feature = "prove")]
    pub fn with_prover(mut self, prover: crate::prove::Prover) -> Self {
        self.prover = prover;
        self
    }

    /// The configured prover (feature `prove`).
    #[cfg(feature = "prove")]
    pub fn prover(&self) -> &crate::prove::Prover {
        &self.prover
    }

    /// Whether Noir print output is forwarded to stdout.
    pub fn shows_output(&self) -> bool {
        self.show_output
    }

    /// The configured oracle resolver URL, if any.
    pub fn oracle_resolver(&self) -> Option<&str> {
        self.oracle_resolver.as_deref()
    }

    /// The configured Noir package directory, if any.
    pub fn program_dir(&self) -> Option<&Path> {
        self.program_dir.as_deref()
    }
}

/// A compiled `#[export]` function, ready to execute.
///
/// Decoding an artifact base64/gzip-decodes and deserializes the bytecode, which is far more
/// expensive than a typical execution, so build a `Program` once and reuse it. It is `Send + Sync`
/// and can live in a `static` (the `nrg!` macro does exactly that).
pub struct Program {
    name: String,
    artifact: ProgramArtifact,
}

impl fmt::Debug for Program {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Program")
            .field("name", &self.name)
            .field("noir_version", &self.artifact.noir_version)
            .finish_non_exhaustive()
    }
}

impl Program {
    /// Decodes an artifact from its JSON text. `name` is used in error messages.
    ///
    /// # Errors
    ///
    /// Fails if `json` is not a Noir program artifact, or was produced by an incompatible Noir
    /// version (the error then names both versions).
    pub fn from_json(name: &str, json: &str) -> Result<Self> {
        let artifact: ProgramArtifact = serde_json::from_str(json).map_err(|err| {
            let found = serde_json::from_str::<serde_json::Value>(json)
                .ok()
                .and_then(|v| v.get("noir_version")?.as_str().map(str::to_owned));
            match found {
                Some(found) if !found.starts_with(crate::NOIR_VERSION) => anyhow!(
                    "cannot decode artifact for `{name}`: it was built by Noir {found}, but this \
                     version of noi executes Noir {} artifacts ({err})",
                    crate::NOIR_VERSION
                ),
                _ => anyhow!("cannot decode artifact for `{name}`: {err}"),
            }
        })?;
        Ok(Self {
            name: name.to_owned(),
            artifact,
        })
    }

    /// Reads and decodes an artifact file. The program is named after the file stem.
    ///
    /// # Errors
    ///
    /// See [`Program::from_json`]; also fails if the file cannot be read.
    pub fn from_file(path: impl AsRef<Path>) -> Result<Self> {
        let path = path.as_ref();
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("<unknown>");
        let json = fs_err::read_to_string(path)?;
        Self::from_json(name, &json)
    }

    /// Function name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Noir compiler version that produced the artifact.
    pub fn noir_version(&self) -> &str {
        &self.artifact.noir_version
    }

    /// The function's ABI, as understood by the Noir toolchain.
    pub fn abi(&self) -> &Abi {
        &self.artifact.abi
    }

    /// Hash of the compiled program, as recorded by the Noir compiler. Changes whenever the
    /// circuit changes; used to key caches such as verification keys.
    pub fn artifact_hash(&self) -> u64 {
        self.artifact.hash
    }

    /// Re-encodes the artifact as JSON (the format `bb` and `nargo` read).
    ///
    /// # Errors
    ///
    /// Fails only if serialization fails.
    pub fn to_json(&self) -> Result<String> {
        serde_json::to_string(&self.artifact).context("serializing program artifact")
    }

    /// Runs the function on `inputs` (keyed by Noir parameter name).
    ///
    /// # Errors
    ///
    /// - Inputs that do not match the ABI (missing/extra parameters, values out of range).
    /// - A failing `assert` or other unsatisfiable constraint. The error is an [`ExecutionError`]
    ///   carrying the assertion message, so callers can `downcast_ref` and inspect it.
    pub fn execute(&self, client: &Client, inputs: &InputMap) -> Result<Execution> {
        let abi = &self.artifact.abi;
        let initial_witness = abi
            .encode(inputs, None)
            .with_context(|| format!("invalid inputs for `{}`", self.name))?;

        // Mocks are a `nargo test` facility; real executions should fail on unknown oracles.
        let output: Box<dyn std::io::Write> = if client.show_output {
            Box::new(std::io::stdout())
        } else {
            Box::new(std::io::sink())
        };
        let mut foreign_calls = DefaultForeignCallBuilder {
            output,
            enable_mocks: false,
            resolver_url: client.oracle_resolver.clone(),
            root_path: client.program_dir.clone(),
            package_name: None,
        }
        .build::<FieldElement>();
        let witness = execute_program(
            &self.artifact.bytecode,
            initial_witness,
            &Bn254BlackBoxSolver,
            &mut foreign_calls,
        )
        .map_err(|err| ExecutionError {
            function: self.name.clone(),
            message: err.user_defined_failure_message(&abi.error_types),
            detail: err.to_string(),
        })?;

        // `execute_program` pushes the entry circuit's witness last.
        let main = witness
            .peek()
            .ok_or_else(|| anyhow!("`{}` produced an empty witness stack", self.name))?;
        let (_, return_value) = abi
            .decode(&main.witness)
            .with_context(|| format!("cannot decode the return value of `{}`", self.name))?;

        Ok(Execution {
            return_value,
            witness,
        })
    }
}

/// The result of [`Program::execute`]: the decoded return value plus the solved witness.
#[derive(Debug)]
pub struct Execution {
    return_value: Option<InputValue>,
    witness: WitnessStack<FieldElement>,
}

impl Execution {
    /// The decoded return value, or `None` for functions returning `()`.
    pub fn return_value(&self) -> Option<&InputValue> {
        self.return_value.as_ref()
    }

    /// Consumes the execution and returns the decoded return value.
    pub fn into_return_value(self) -> Option<InputValue> {
        self.return_value
    }

    /// The full solved witness stack (one entry per ACIR circuit that was executed).
    pub fn witness_stack(&self) -> &WitnessStack<FieldElement> {
        &self.witness
    }

    /// Serializes the witness stack in the gzip-compressed format `nargo execute` writes to
    /// `target/<name>.gz`, which is what Barretenberg's `bb prove -w` consumes.
    ///
    /// # Errors
    ///
    /// Fails only if serialization fails.
    pub fn witness_bytes(&self) -> Result<Vec<u8>> {
        self.witness.serialize().map_err(|err| anyhow!("{err}"))
    }
}

/// A Noir function failed to execute, typically due to a failing `assert`.
///
/// Returned (inside `anyhow::Error`) from [`Program::execute`] and generated `simulate`
/// functions. Downcast to match on the assertion message:
///
/// ```ignore
/// match demo::withdraw::simulate(&client, args) {
///     Err(e) if e.downcast_ref::<noi::ExecutionError>()
///         .and_then(|e| e.message()) == Some("insufficient balance") => { /* … */ }
///     other => { other?; }
/// }
/// ```
#[derive(Debug)]
pub struct ExecutionError {
    function: String,
    message: Option<String>,
    detail: String,
}

impl ExecutionError {
    /// Name of the function that failed.
    pub fn function(&self) -> &str {
        &self.function
    }

    /// The user-provided assertion message (`assert(cond, "message")`), if any.
    pub fn message(&self) -> Option<&str> {
        self.message.as_deref()
    }
}

impl fmt::Display for ExecutionError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.message {
            Some(message) => write!(f, "`{}` failed: {message}", self.function),
            None => write!(f, "`{}` failed: {}", self.function, self.detail),
        }
    }
}

impl std::error::Error for ExecutionError {}

/// Converts a Rust value into Noir's [`InputValue`] representation.
///
/// Implemented for `bool`, unsigned and signed integers, [`FieldElement`], `String`/`str`,
/// fixed-size arrays, tuples up to arity 8, and structs generated by `nrg!`. Signed integers are
/// encoded in two's complement at their bit width, matching the Noir ABI.
pub trait ToInputValue {
    /// Performs the conversion.
    fn to_input_value(&self) -> InputValue;
}

/// Converts Noir's [`InputValue`] back into a Rust value.
///
/// The counterpart of [`ToInputValue`].
pub trait FromOutputValue: Sized {
    /// Performs the conversion.
    ///
    /// # Errors
    ///
    /// Fails if `value` has the wrong shape or does not fit in `Self`.
    fn from_output_value(value: InputValue) -> Result<Self>;
}

impl<T: ToInputValue + ?Sized> ToInputValue for &T {
    fn to_input_value(&self) -> InputValue {
        (**self).to_input_value()
    }
}

fn expect_field(value: InputValue, ty: &str) -> Result<FieldElement> {
    match value {
        InputValue::Field(field) => Ok(field),
        other => Err(anyhow!(
            "expected a field element for `{ty}`, got {other:?}"
        )),
    }
}

impl ToInputValue for bool {
    fn to_input_value(&self) -> InputValue {
        InputValue::Field(FieldElement::from(u128::from(*self)))
    }
}

impl FromOutputValue for bool {
    fn from_output_value(value: InputValue) -> Result<Self> {
        let field = expect_field(value, "bool")?;
        if field.is_zero() {
            Ok(false)
        } else if field.is_one() {
            Ok(true)
        } else {
            Err(anyhow!("expected 0 or 1 for `bool`, got {field}"))
        }
    }
}

macro_rules! impl_unsigned {
    ($($ty:ty),+) => {$(
        impl ToInputValue for $ty {
            fn to_input_value(&self) -> InputValue {
                InputValue::Field(FieldElement::from(*self as u128))
            }
        }

        impl FromOutputValue for $ty {
            fn from_output_value(value: InputValue) -> Result<Self> {
                let field = expect_field(value, stringify!($ty))?;
                field
                    .try_into_u128()
                    .and_then(|v| <$ty>::try_from(v).ok())
                    .ok_or_else(|| anyhow!("{field} does not fit into `{}`", stringify!($ty)))
            }
        }
    )+};
}

macro_rules! impl_signed {
    ($($ty:ty => $uty:ty),+) => {$(
        impl ToInputValue for $ty {
            fn to_input_value(&self) -> InputValue {
                // Two's complement at the type's own width, as the Noir ABI expects.
                InputValue::Field(FieldElement::from(*self as $uty as u128))
            }
        }

        impl FromOutputValue for $ty {
            fn from_output_value(value: InputValue) -> Result<Self> {
                let field = expect_field(value, stringify!($ty))?;
                field
                    .try_into_u128()
                    .and_then(|v| <$uty>::try_from(v).ok())
                    .map(|raw| raw as $ty)
                    .ok_or_else(|| anyhow!("{field} does not fit into `{}`", stringify!($ty)))
            }
        }
    )+};
}

impl_unsigned!(u8, u16, u32, u64, u128, usize);
impl_signed!(i8 => u8, i16 => u16, i32 => u32, i64 => u64, i128 => u128, isize => usize);

impl ToInputValue for FieldElement {
    fn to_input_value(&self) -> InputValue {
        InputValue::Field(*self)
    }
}

impl FromOutputValue for FieldElement {
    fn from_output_value(value: InputValue) -> Result<Self> {
        expect_field(value, "Field")
    }
}

impl ToInputValue for str {
    fn to_input_value(&self) -> InputValue {
        InputValue::String(self.to_owned())
    }
}

impl ToInputValue for String {
    fn to_input_value(&self) -> InputValue {
        InputValue::String(self.clone())
    }
}

impl FromOutputValue for String {
    fn from_output_value(value: InputValue) -> Result<Self> {
        match value {
            InputValue::String(s) => Ok(s),
            // Return values are decoded as raw bytes; reassemble them.
            InputValue::Vec(bytes) => {
                let bytes = bytes
                    .into_iter()
                    .map(u8::from_output_value)
                    .collect::<Result<Vec<_>>>()?;
                String::from_utf8(bytes).context("Noir string is not valid UTF-8")
            }
            other => Err(anyhow!("expected a string, got {other:?}")),
        }
    }
}

impl<T: ToInputValue, const N: usize> ToInputValue for [T; N] {
    fn to_input_value(&self) -> InputValue {
        InputValue::Vec(self.iter().map(ToInputValue::to_input_value).collect())
    }
}

impl<T: FromOutputValue, const N: usize> FromOutputValue for [T; N] {
    fn from_output_value(value: InputValue) -> Result<Self> {
        let InputValue::Vec(values) = value else {
            return Err(anyhow!("expected an array of length {N}, got {value:?}"));
        };
        if values.len() != N {
            return Err(anyhow!(
                "expected an array of length {N}, got {}",
                values.len()
            ));
        }
        let items = values
            .into_iter()
            .map(T::from_output_value)
            .collect::<Result<Vec<_>>>()?;
        // Length was checked above, so this cannot fail.
        items
            .try_into()
            .map_err(|_| anyhow!("array length mismatch"))
    }
}

macro_rules! impl_tuple {
    ($len:literal: $($name:ident),+) => {
        #[allow(non_snake_case)]
        impl<$($name: ToInputValue),+> ToInputValue for ($($name,)+) {
            fn to_input_value(&self) -> InputValue {
                let ($($name,)+) = self;
                InputValue::Vec(vec![$($name.to_input_value()),+])
            }
        }

        #[allow(non_snake_case)]
        impl<$($name: FromOutputValue),+> FromOutputValue for ($($name,)+) {
            fn from_output_value(value: InputValue) -> Result<Self> {
                let InputValue::Vec(values) = value else {
                    return Err(anyhow!("expected a tuple of length {}, got {value:?}", $len));
                };
                let [$($name),+]: [InputValue; $len] = values.try_into().map_err(|v: Vec<_>| {
                    anyhow!("expected a tuple of length {}, got {}", $len, v.len())
                })?;
                Ok(($($name::from_output_value($name)?,)+))
            }
        }
    };
}

impl_tuple!(1: A);
impl_tuple!(2: A, B);
impl_tuple!(3: A, B, C);
impl_tuple!(4: A, B, C, D);
impl_tuple!(5: A, B, C, D, E);
impl_tuple!(6: A, B, C, D, E, F);
impl_tuple!(7: A, B, C, D, E, F, G);
impl_tuple!(8: A, B, C, D, E, F, G, H);

impl ToInputValue for () {
    fn to_input_value(&self) -> InputValue {
        InputValue::Vec(Vec::new())
    }
}

impl FromOutputValue for () {
    fn from_output_value(_: InputValue) -> Result<Self> {
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn round_trip<T>(value: T)
    where
        T: ToInputValue + FromOutputValue + PartialEq + fmt::Debug,
    {
        let encoded = value.to_input_value();
        assert_eq!(T::from_output_value(encoded).unwrap(), value);
    }

    #[test]
    fn scalars_round_trip() {
        round_trip(true);
        round_trip(u8::MAX);
        round_trip(u128::MAX);
        round_trip(-1i8);
        round_trip(i64::MIN);
        round_trip(FieldElement::from(42u128));
        round_trip(String::from("noir"));
    }

    #[test]
    fn signed_uses_twos_complement_at_width() {
        let InputValue::Field(f) = (-1i32).to_input_value() else {
            unreachable!()
        };
        assert_eq!(f.try_into_u128(), Some(u32::MAX as u128));
    }

    #[test]
    fn aggregates_round_trip() {
        round_trip([1u16, 2, 3]);
        round_trip((7u32, false));
        round_trip((1u8, (2u16, [true, false]), -3i32));
    }

    #[test]
    fn shape_errors_are_reported() {
        let err = <[u8; 2]>::from_output_value([1u8, 2, 3].to_input_value()).unwrap_err();
        assert!(err.to_string().contains("length 2"), "{err}");
        let err = u8::from_output_value(300u32.to_input_value()).unwrap_err();
        assert!(err.to_string().contains("u8"), "{err}");
    }
}
