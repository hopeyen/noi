/// A Noir value, as passed to or returned from a function.
///
/// Mirrors `noirc_abi::input_parser::InputValue`. Arrays and tuples are both [`Value::Array`];
/// `bool` and every integer type are [`Value::Field`].
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum Value {
    /// A `Field`, integer, or `bool`.
    Field(FieldElement),
    /// A `str<N>`.
    String(String),
    /// An array `[T; N]` or a tuple.
    Array(Vec<Value>),
    /// A struct, keyed by field name.
    Struct(BTreeMap<String, Value>),
}

impl Value {
    pub(crate) fn kind(&self) -> &'static str {
        match self {
            Value::Field(_) => "a field element",
            Value::String(_) => "a string",
            Value::Array(_) => "an array or tuple",
            Value::Struct(_) => "a struct",
        }
    }
}

/// Function inputs keyed by Noir parameter name.
pub type InputMap = BTreeMap<String, Value>;

/// One argument or result of an oracle call: a single field element or an array of them.
///
/// Mirrors `acvm::acir::brillig::ForeignCallParam`.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum OracleValue {
    /// A single value.
    Field(FieldElement),
    /// An array (or vector) of values.
    Array(Vec<FieldElement>),
}

type OracleFn = dyn Fn(&[OracleValue]) -> Result<Vec<OracleValue>> + Send + Sync;

/// Execution settings shared by every call.
///
/// `Client` is cheap to clone (handlers are reference-counted), holds no open resources, and is
/// `Send + Sync`, so one client can serve many threads.
///
/// ```
/// use noi_core::runtime::{Client, OracleValue};
///
/// let client = Client::new().with_oracle("get_price", |_args| {
///     Ok(vec![OracleValue::Field(1_000u128.into())])
/// });
/// assert!(client.has_oracle("get_price"));
/// ```
#[derive(Clone, Default)]
pub struct Client {
    oracles: BTreeMap<String, Arc<OracleFn>>,
    #[cfg(feature = "prove")]
    prover: crate::prove::Prover,
}

impl fmt::Debug for Client {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut s = f.debug_struct("Client");
        s.field("oracles", &self.oracles.keys().collect::<Vec<_>>());
        #[cfg(feature = "prove")]
        s.field("prover", &self.prover);
        s.finish()
    }
}

impl Client {
    /// Creates a client with no oracle handlers and (with `prove`) the default [`Prover`](crate::prove::Prover).
    pub fn new() -> Self {
        Self::default()
    }

    /// Handles calls to the Noir oracle `name` with `handler`.
    ///
    /// The handler receives the oracle's arguments and returns its results, in order. Returning an
    /// error fails the execution with an [`ExecutionError`] whose [`detail`](ExecutionError::detail)
    /// names the oracle and includes the handler's message (with its context chain); the handler's
    /// error value itself is not kept. Registering a name twice replaces the handler;
    /// registering `print` overrides the default of discarding print output.
    pub fn with_oracle<F>(mut self, name: impl Into<String>, handler: F) -> Self
    where
        F: Fn(&[OracleValue]) -> Result<Vec<OracleValue>> + Send + Sync + 'static,
    {
        self.oracles.insert(name.into(), Arc::new(handler));
        self
    }

    /// Whether a handler is registered for the oracle `name`.
    pub fn has_oracle(&self, name: &str) -> bool {
        self.oracles.contains_key(name)
    }

    /// Proving settings used by generated `prove`/`verify` functions (feature `prove`).
    #[cfg(feature = "prove")]
    pub fn with_prover(mut self, prover: crate::prove::Prover) -> Self {
        self.prover = prover;
        self
    }

    /// The configured prover (feature `prove`).
    #[cfg(feature = "prove")]
    pub fn prover(&self) -> &crate::prove::Prover {
        &self.prover
    }

    pub(crate) fn call_oracle(&self, name: &str, args: &[OracleValue]) -> Result<Vec<OracleValue>> {
        match self.oracles.get(name) {
            Some(handler) => handler(args),
            // Noir's `print`/`println` lower to this oracle; output is discarded by default.
            None if name == "print" => Ok(Vec::new()),
            None => Err(anyhow!(
                "no handler for oracle `{name}`; register one with `Client::with_oracle`"
            )),
        }
    }
}

/// A compiled `#[export]` function, ready to execute.
///
/// Decoding an artifact base64/gzip-decodes and deserializes the bytecode, which is far more
/// expensive than a typical execution, so build a `Program` once and reuse it. It is `Send + Sync`
/// and can live in a `static` (the `nrg!` macro does exactly that).
pub struct Program {
    function: ExportFunction,
    noir_version: String,
    hash: u64,
    error_types: BTreeMap<u64, ErrorType>,
    bytecode: AcirProgram<FieldElement>,
    json: Box<str>,
}

impl fmt::Debug for Program {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Program")
            .field("name", &self.function.name)
            .field("noir_version", &self.noir_version)
            .finish_non_exhaustive()
    }
}

#[derive(Deserialize)]
struct RawArtifact {
    noir_version: String,
    #[serde(deserialize_with = "hash_from_string_or_number")]
    hash: u64,
    abi: ParsedAbi,
    #[serde(deserialize_with = "AcirProgram::deserialize_program_base64")]
    bytecode: AcirProgram<FieldElement>,
}

/// `noirc_artifacts` writes the hash as a decimal string; older artifacts used a number.
fn hash_from_string_or_number<'de, D: serde::Deserializer<'de>>(d: D) -> Result<u64, D::Error> {
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum Hash {
        Number(u64),
        String(String),
    }
    match Hash::deserialize(d)? {
        Hash::Number(n) => Ok(n),
        Hash::String(s) => s.parse().map_err(serde::de::Error::custom),
    }
}

impl Program {
    /// Decodes an artifact from its JSON text. `name` is the function name, used in error messages
    /// and by generated code.
    ///
    /// # Errors
    ///
    /// Fails if `json` is not a Noir program artifact, or if it was produced by a Noir release
    /// other than [`NOIR_VERSION`](crate::NOIR_VERSION) (see [`crate::noir_version_compatible`]).
    pub fn from_json(name: &str, json: &str) -> Result<Self> {
        let found = serde_json::from_str::<serde_json::Value>(json)
            .ok()
            .and_then(|v| v.get("noir_version")?.as_str().map(str::to_owned));
        if let Some(found) = &found {
            if !crate::noir_version_compatible(found) {
                return Err(anyhow!(
                    "artifact for `{name}` was built by Noir {found}, but this version of noi \
                     executes Noir {} artifacts; re-export it with that `nargo`",
                    crate::NOIR_VERSION
                ));
            }
        }
        let raw: RawArtifact = serde_json::from_str(json)
            .with_context(|| format!("cannot decode the artifact for `{name}`"))?;
        let mut function = raw.abi.function;
        function.name = name.to_owned();
        function.noir_version = Some(raw.noir_version.clone());
        Ok(Self {
            function,
            noir_version: raw.noir_version,
            hash: raw.hash,
            error_types: raw.abi.error_types,
            bytecode: raw.bytecode,
            json: json.into(),
        })
    }

    /// Reads and decodes an artifact file. The program is named after the file stem, as
    /// `nargo export` names its output.
    ///
    /// # Errors
    ///
    /// See [`Program::from_json`]; also fails if the file cannot be read.
    pub fn from_file(path: impl AsRef<Path>) -> Result<Self> {
        let path = path.as_ref();
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or_else(|| anyhow!("`{}` has no UTF-8 file name", path.display()))?;
        let json = fs_err::read_to_string(path)?;
        Self::from_json(name, &json)
    }

    /// Function name.
    pub fn name(&self) -> &str {
        &self.function.name
    }

    /// Noir compiler version that produced the artifact (e.g. `1.0.0+275d3ab1…`).
    pub fn noir_version(&self) -> &str {
        &self.noir_version
    }

    /// Parameter and return types, as also used by `nrg!`.
    pub fn function(&self) -> &ExportFunction {
        &self.function
    }

    /// Noir's fingerprint of the monomorphized program, as recorded in the artifact.
    ///
    /// It is computed before SSA/ACIR generation and does not cover the compiler version or
    /// codegen options, so it does **not** identify the circuit; use it only as a hint.
    pub fn artifact_hash(&self) -> u64 {
        self.hash
    }

    /// Number of ACIR circuits in the program (more than one when it calls `#[fold]` functions).
    #[cfg_attr(not(feature = "prove"), allow(dead_code))]
    pub(crate) fn circuit_count(&self) -> usize {
        self.bytecode.functions.len()
    }

    /// The artifact's original JSON text (the format `bb` and `nargo` read).
    pub fn artifact_json(&self) -> &str {
        &self.json
    }

    /// Runs the function on `inputs` (keyed by Noir parameter name).
    ///
    /// # Errors
    ///
    /// - Inputs that do not match the ABI (missing or extra parameters, wrong shapes, values out of
    ///   range). The error names the offending path, e.g. `` `p.x` ``.
    /// - A failing `assert`, an unsatisfiable constraint, or a failing oracle. The error is an
    ///   [`ExecutionError`], which callers can `downcast_ref` to read the assertion message.
    pub fn execute(&self, client: &Client, inputs: &InputMap) -> Result<Execution> {
        let initial_witness = abi::encode_inputs(&self.function, inputs)
            .with_context(|| format!("invalid inputs for `{}`", self.function.name))?;
        let witness = executor::execute(&self.bytecode, initial_witness, client, &self.error_types)
            .map_err(|failure| ExecutionError {
                function: self.function.name.clone(),
                message: failure.message,
                detail: failure.detail,
            })?;
        // The entry circuit's witness is pushed last.
        let main = witness
            .peek()
            .ok_or_else(|| anyhow!("`{}` produced an empty witness stack", self.function.name))?;
        let return_value =
            abi::decode_return(&self.function, &main.witness).with_context(|| {
                format!("cannot decode the return value of `{}`", self.function.name)
            })?;
        Ok(Execution {
            return_value,
            witness,
        })
    }
}

/// The result of [`Program::execute`]: the decoded return value plus the solved witness.
#[derive(Debug)]
pub struct Execution {
    return_value: Option<Value>,
    witness: WitnessStack<FieldElement>,
}

impl Execution {
    /// The decoded return value, or `None` for functions returning `()`.
    pub fn return_value(&self) -> Option<&Value> {
        self.return_value.as_ref()
    }

    /// Consumes the execution and returns the decoded return value.
    pub fn into_return_value(self) -> Option<Value> {
        self.return_value
    }

    /// The full solved witness stack (one entry per ACIR circuit that was executed).
    pub fn witness_stack(&self) -> &WitnessStack<FieldElement> {
        &self.witness
    }

    /// Serializes the witness stack in the gzip-compressed format `nargo execute` writes to
    /// `target/<name>.gz`, which is what Barretenberg's `bb prove -w` consumes.
    ///
    /// # Errors
    ///
    /// Fails only if serialization fails.
    pub fn witness_bytes(&self) -> Result<Vec<u8>> {
        self.witness.serialize().map_err(|err| anyhow!("{err}"))
    }
}

/// A Noir function failed to execute: a failing `assert`, an unsatisfiable constraint, or a
/// failing oracle.
///
/// Returned (inside `anyhow::Error`) from [`Program::execute`] and generated `simulate`
/// functions. Downcast to match on the assertion message:
///
/// ```
/// # use noi_core::runtime::*;
/// # let program = Program::from_file(concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/demo/checked_div.json"))?;
/// // Noir: assert(b != 0, "division by zero");
/// let inputs = InputMap::from([("a".to_string(), 1u32.to_value()), ("b".to_string(), 0u32.to_value())]);
/// let err = program.execute(&Client::new(), &inputs).unwrap_err();
/// let exec = err.downcast_ref::<ExecutionError>().unwrap();
/// assert_eq!(exec.message(), Some("division by zero"));
/// # Ok::<(), anyhow::Error>(())
/// ```
#[derive(Debug)]
pub struct ExecutionError {
    function: String,
    message: Option<String>,
    detail: String,
}

impl ExecutionError {
    /// Name of the function that failed.
    pub fn function(&self) -> &str {
        &self.function
    }

    /// The assertion message, if the failure was an `assert` with one. Format strings
    /// (`assert(x, f"{x} too big")`) are filled in.
    pub fn message(&self) -> Option<&str> {
        self.message.as_deref()
    }

    /// The underlying solver error, e.g. which opcode failed.
    pub fn detail(&self) -> &str {
        &self.detail
    }
}

impl fmt::Display for ExecutionError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.message {
            Some(message) => write!(f, "`{}` failed: {message}", self.function),
            None => write!(f, "`{}` failed: {}", self.function, self.detail),
        }
    }
}

impl std::error::Error for ExecutionError {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_oracles_fail_and_print_is_ignored() {
        let client = Client::new();
        assert!(client.call_oracle("print", &[]).unwrap().is_empty());
        let err = client.call_oracle("get_price", &[]).unwrap_err();
        assert!(err.to_string().contains("get_price"), "{err}");
    }

    #[test]
    fn registered_oracles_are_called() {
        let client = Client::new().with_oracle("double", |args| match args {
            [OracleValue::Field(x)] => Ok(vec![OracleValue::Field(*x + *x)]),
            _ => Err(anyhow!("bad args")),
        });
        let out = client
            .call_oracle("double", &[OracleValue::Field(21u128.into())])
            .unwrap();
        assert_eq!(out, [OracleValue::Field(42u128.into())]);
    }

    #[test]
    fn client_and_program_are_thread_safe() {
        fn assert_send_sync<T: Send + Sync>() {}
        assert_send_sync::<Client>();
        assert_send_sync::<Program>();
        assert_send_sync::<ExecutionError>();
    }
}
