//! Executing exported Noir functions from Rust (feature `runner`, on by default).
//!
//! The runtime works directly on the program artifact that `nargo export` produced, so neither the
//! Noir sources nor `nargo` are needed at run time:
//!
//! 1. [`Program::from_json`] decodes the artifact (ACIR bytecode + ABI) once.
//! 2. [`Program::execute`] ABI-encodes an [`InputMap`], solves every circuit of the program with
//!    the ACVM and the BN254 black-box solver, and decodes the return value.
//! 3. [`ToValue`] / [`FromValue`] convert between Rust values and Noir's [`Value`] representation.
//!
//! Only crates published on crates.io (`acvm`, `bn254_blackbox_solver`) are used; the pieces of
//! `nargo` and `noirc_abi` that are not published (ABI encoding, the multi-circuit executor,
//! assertion-message decoding) are reimplemented here against Noir [`NOIR_VERSION`](crate::NOIR_VERSION).
//!
//! Code generated by `nrg!` wraps these steps in a typed `simulate` function and caches the parsed
//! [`Program`] in a `static`, so you rarely need this module directly. It is public for tooling and
//! for programs whose exports are only known at run time.
//!
//! # Example
//!
//! ```
//! use noi_core::runtime::{Client, FromValue, InputMap, Program, ToValue};
//!
//! # let path = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/demo/add.json");
//! let program = Program::from_file(path)?;
//!
//! let inputs = InputMap::from([
//!     ("a".to_string(), 2u32.to_value()),
//!     ("b".to_string(), 3u32.to_value()),
//! ]);
//! let execution = program.execute(&Client::new(), &inputs)?;
//! let sum = u32::from_value(execution.into_return_value().unwrap())?;
//! assert_eq!(sum, 5);
//! # Ok::<(), anyhow::Error>(())
//! ```
//!
//! # Oracles
//!
//! Unconstrained Noir code can call oracles (`#[oracle(name)] unconstrained fn ...`). Register a
//! handler per oracle name with [`Client::with_oracle`]. `print`/`println` calls are accepted and
//! discarded; any other unhandled oracle fails the execution with an error naming it.

pub(crate) mod abi;
mod convert;
mod executor;

